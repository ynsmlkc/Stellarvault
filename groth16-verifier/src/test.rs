fn setup() -> (Env, Groth16VerifierClient<'static>) {
    let env = Env::default();
    let id = env.register(Groth16Verifier, ());
    let client = Groth16VerifierClient::new(&env, &id);
    (env.clone(), client)
}

fn proof(env: &Env) -> Proof {
    Proof {
        a: BytesN::from_array(env, &PROOF_A),
        b: BytesN::from_array(env, &PROOF_B),
        c: BytesN::from_array(env, &PROOF_C),
    }
}

fn public_inputs(env: &Env) -> Vec<U256> {
    let mut v = Vec::new(env);
    for raw in PUBLIC.iter() {
        v.push_back(U256::from_be_bytes(env, &soroban_sdk::Bytes::from_array(env, raw)));
    }
    v
}

#[test]
fn valid_proof_verifies() {
    let (env, c) = setup();
    assert!(c.verify(&proof(&env), &public_inputs(&env)));
}

#[test]
fn tampered_nullifier_is_rejected() {
    let (env, c) = setup();
    let mut inputs = public_inputs(&env);
    // nullifier is the 4th public signal — claim a different one
    let n = inputs.get(3).unwrap();
    inputs.set(3, n.add(&U256::from_u32(&env, 1)));
    assert!(!c.verify(&proof(&env), &inputs));
}

#[test]
fn tampered_signer_root_is_rejected() {
    let (env, c) = setup();
    let mut inputs = public_inputs(&env);
    let r = inputs.get(2).unwrap();
    inputs.set(2, r.add(&U256::from_u32(&env, 1)));
    assert!(!c.verify(&proof(&env), &inputs));
}

#[test]
fn proof_from_another_statement_is_rejected() {
    let (env, c) = setup();
    // swap two public inputs: individually valid field elements, wrong statement
    let mut inputs = public_inputs(&env);
    let a = inputs.get(0).unwrap();
    let b = inputs.get(1).unwrap();
    inputs.set(0, b);
    inputs.set(1, a);
    assert!(!c.verify(&proof(&env), &inputs));
}

#[test]
fn wrong_public_input_count_errors() {
    let (env, c) = setup();
    let short = vec![&env, U256::from_u32(&env, 1)];
    assert_eq!(c.try_verify(&proof(&env), &short), Err(Ok(Error::WrongPublicInputCount)));
}

#[test]
fn n_public_matches_the_circuit() {
    let (_env, c) = setup();
    assert_eq!(c.n_public(), 4);
}
